let _id = 0
function item(legendId: LegendId, name: string, rarity: Rarity, category: ItemCategory): Item {
  return { id: `${legendId}_${_id++}`, name, category, rarity, legendId }
}
function skins(legendId: LegendId, legendary: string[], epic: string[], rare: string[], common: string[]): Item[] {
  return [
    ...legendary.map(n => item(legendId, n, 'legendary', 'legend_skin')),
    ...epic.map(n => item(legendId, n, 'epic', 'legend_skin')),
    ...rare.map(n => item(legendId, n, 'rare', 'legend_skin')),
    ...common.map(n => item(legendId, n, 'common', 'legend_skin')),
  ]
}

